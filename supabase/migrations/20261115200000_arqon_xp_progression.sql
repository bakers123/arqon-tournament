-- Persistent ARQON XP ledger, source-driven rewards, and milestone bonuses.
create table if not exists public.arqon_xp_events (
  id bigint generated by default as identity primary key,
  arqon_id bigint not null references public.profiles(arqon_id) on delete cascade,
  source_type text not null check (source_type in ('tournament','live_match','achievement')),
  source_key text not null,
  source_label text not null default '',
  xp_amount integer not null check (xp_amount between 1 and 1000),
  created_at timestamptz not null default now(),
  unique(arqon_id,source_type,source_key)
);
create index if not exists arqon_xp_events_profile_date on public.arqon_xp_events(arqon_id,created_at desc);
alter table public.arqon_xp_events enable row level security;
grant select on public.arqon_xp_events to anon,authenticated;
drop policy if exists "Players can read public XP" on public.arqon_xp_events;
create policy "Players can read public XP" on public.arqon_xp_events
for select to anon,authenticated using (
 exists(select 1 from public.profiles p where p.arqon_id=arqon_xp_events.arqon_id
   and (p.is_public=true or p.user_id=(select auth.uid())))
);
revoke insert,update,delete on public.arqon_xp_events from anon,authenticated;

create or replace function public.award_arqon_xp_milestones()
returns trigger language plpgsql security definer set search_path=''
as $$
declare total_xp integer;
begin
 if new.source_type='achievement' then return new; end if;
 select coalesce(sum(xp_amount),0)::integer into total_xp
 from public.arqon_xp_events where arqon_id=new.arqon_id;
 insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
 select new.arqon_id,'achievement',m.key,m.label,m.bonus
 from (values
   ('xp_500','Достижение: 500 XP',25,500),
   ('xp_1500','Достижение: 1 500 XP',50,1500),
   ('xp_3000','Достижение: 3 000 XP',75,3000),
   ('xp_6000','Достижение: 6 000 XP',100,6000),
   ('xp_10000','Достижение: 10 000 XP',150,10000)
 ) as m(key,label,bonus,threshold)
 where total_xp>=m.threshold
 on conflict(arqon_id,source_type,source_key) do nothing;
 return new;
end;
$$;
drop trigger if exists arqon_xp_milestones_after_insert on public.arqon_xp_events;
create trigger arqon_xp_milestones_after_insert after insert on public.arqon_xp_events
for each row execute function public.award_arqon_xp_milestones();

create or replace function public.sync_arqon_tournament_xp()
returns trigger language plpgsql security definer set search_path=''
as $$
declare r record;
begin
 if tg_op='DELETE' then
   delete from public.arqon_xp_events where source_type='tournament' and source_key=old.id::text;
   return old;
 end if;
 if tg_op='UPDATE' then
   delete from public.arqon_xp_events where source_type='tournament' and source_key=old.id::text;
 end if;
 for r in
   select pr.arqon_id,
     (case when bool_or(lower(btrim(pl.name))=lower(btrim(new.place_1))) then 100
           when bool_or(lower(btrim(pl.name))=lower(btrim(new.place_2))) then 70
           when bool_or(lower(btrim(pl.name))=lower(btrim(new.place_3))) then 50 else 0 end)
       + (case when bool_or(new.mvp is not null and lower(btrim(pl.name))=lower(btrim(new.mvp))) then 50 else 0 end) as xp
   from public.players pl join public.profiles pr on pr.user_id::text=pl.uid
   where lower(btrim(pl.name)) in (lower(btrim(new.place_1)),lower(btrim(new.place_2)),lower(btrim(new.place_3)),lower(btrim(coalesce(new.mvp,''))))
   group by pr.arqon_id
 loop
   if r.xp>0 then
     insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
     values(r.arqon_id,'tournament',new.id::text,coalesce(new.tournament_name,'Турнир ARQON'),r.xp)
     on conflict(arqon_id,source_type,source_key) do nothing;
   end if;
 end loop;
 return new;
end;
$$;
drop trigger if exists arqon_tournament_xp_sync on public.results;
create trigger arqon_tournament_xp_sync after insert or update or delete on public.results
for each row execute function public.sync_arqon_tournament_xp();

create or replace function public.award_arqon_live_match_xp()
returns trigger language plpgsql security definer set search_path=''
as $$
declare target_id bigint; label text;
begin
 select pr.arqon_id into target_id
 from public.players pl join public.profiles pr on pr.user_id::text=pl.uid
 where lower(btrim(pl.name))=lower(btrim(new.player_name))
 order by pr.arqon_id limit 1;
 if target_id is not null then
   select coalesce(title,'Матч Live Center') into label from public.live_matches where id=new.live_match_id;
   insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
   values(target_id,'live_match',new.live_match_id::text,coalesce(label,'Матч Live Center'),10)
   on conflict(arqon_id,source_type,source_key) do nothing;
 end if;
 return new;
end;
$$;
drop trigger if exists arqon_live_match_xp_sync on public.live_match_player_stats;
create trigger arqon_live_match_xp_sync after insert on public.live_match_player_stats
for each row execute function public.award_arqon_live_match_xp();

-- Backfill published tournament results.
insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
select pr.arqon_id,'tournament',r.id::text,coalesce(r.tournament_name,'Турнир ARQON'),
 case when lower(btrim(pl.name))=lower(btrim(r.place_1)) then 100
      when lower(btrim(pl.name))=lower(btrim(r.place_2)) then 70
      when lower(btrim(pl.name))=lower(btrim(r.place_3)) then 50 else 0 end
 + case when r.mvp is not null and lower(btrim(pl.name))=lower(btrim(r.mvp)) then 50 else 0 end
from public.results r
join public.players pl on lower(btrim(pl.name)) in (lower(btrim(r.place_1)),lower(btrim(r.place_2)),lower(btrim(r.place_3)),lower(btrim(coalesce(r.mvp,''))))
join public.profiles pr on pr.user_id::text=pl.uid
on conflict(arqon_id,source_type,source_key) do nothing;

-- Backfill existing Live Center match participation.
insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
select distinct on (pr.arqon_id,ls.live_match_id)
 pr.arqon_id,'live_match',ls.live_match_id::text,coalesce(lm.title,'Матч Live Center'),10
from public.live_match_player_stats ls
join public.players pl on lower(btrim(pl.name))=lower(btrim(ls.player_name))
join public.profiles pr on pr.user_id::text=pl.uid
left join public.live_matches lm on lm.id=ls.live_match_id
order by pr.arqon_id,ls.live_match_id,ls.created_at
on conflict(arqon_id,source_type,source_key) do nothing;


create or replace function public.sync_arqon_live_mvp_xp()
returns trigger language plpgsql security definer set search_path=''
as $$
declare target_id bigint;
begin
 if tg_op='UPDATE' and old.mvp_name is not null and old.mvp_name is distinct from new.mvp_name then
   select pr.arqon_id into target_id from public.players pl join public.profiles pr on pr.user_id::text=pl.uid
   where lower(btrim(pl.name))=lower(btrim(old.mvp_name)) order by pr.arqon_id limit 1;
   if target_id is not null then
     delete from public.arqon_xp_events where arqon_id=target_id and source_type='live_match' and source_key=old.id::text||':mvp';
   end if;
 end if;
 if new.mvp_name is not null and (tg_op='INSERT' or old.mvp_name is distinct from new.mvp_name) then
   select pr.arqon_id into target_id from public.players pl join public.profiles pr on pr.user_id::text=pl.uid
   where lower(btrim(pl.name))=lower(btrim(new.mvp_name)) order by pr.arqon_id limit 1;
   if target_id is not null then
     insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
     values(target_id,'live_match',new.id::text||':mvp',coalesce(new.title,'MVP матча Live Center'),50)
     on conflict(arqon_id,source_type,source_key) do nothing;
   end if;
 end if;
 return new;
end;
$$;
drop trigger if exists arqon_live_match_mvp_xp_sync on public.live_matches;
create trigger arqon_live_match_mvp_xp_sync after insert or update of mvp_name on public.live_matches
for each row execute function public.sync_arqon_live_mvp_xp();
insert into public.arqon_xp_events(arqon_id,source_type,source_key,source_label,xp_amount)
select pr.arqon_id,'live_match',lm.id::text||':mvp',coalesce(lm.title,'MVP матча Live Center'),50
from public.live_matches lm
join public.players pl on lower(btrim(pl.name))=lower(btrim(lm.mvp_name))
join public.profiles pr on pr.user_id::text=pl.uid
where lm.mvp_name is not null
on conflict(arqon_id,source_type,source_key) do nothing;
