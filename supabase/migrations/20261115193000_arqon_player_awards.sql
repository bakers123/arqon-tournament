create table if not exists public.arqon_player_awards (
  id bigint generated by default as identity primary key,
  arqon_id bigint not null references public.profiles(arqon_id) on delete cascade,
  award_key text not null check (award_key in ('founder','community','event_mvp','champion','fair_play','legend')),
  award_name text not null,
  award_description text not null default '',
  award_icon text not null default '🏅',
  rarity text not null check (rarity in ('common','rare','epic','legendary')),
  reason text not null check (char_length(btrim(reason)) between 3 and 300),
  granted_by uuid not null references auth.users(id),
  granted_at timestamptz not null default now(),
  revoked_by uuid references auth.users(id),
  revoked_at timestamptz,
  revoke_reason text,
  constraint arqon_award_revoke_reason_length check (revoke_reason is null or char_length(revoke_reason)<=300)
);
create unique index if not exists arqon_player_awards_one_active_per_type
  on public.arqon_player_awards(arqon_id,award_key) where revoked_at is null;
create index if not exists arqon_player_awards_profile_history
  on public.arqon_player_awards(arqon_id,granted_at desc);
alter table public.arqon_player_awards enable row level security;
grant select on public.arqon_player_awards to anon, authenticated;
grant insert,update on public.arqon_player_awards to authenticated;
create policy "Public can read active ARQON awards"
  on public.arqon_player_awards for select to anon,authenticated
  using (revoked_at is null or (select public.current_organizer_role()) in ('owner','admin','editor'));
create policy "Organizers can grant ARQON awards"
  on public.arqon_player_awards for insert to authenticated
  with check ((select public.current_organizer_role()) in ('owner','admin','editor') and granted_by=(select auth.uid()) and revoked_at is null and revoked_by is null);
create or replace function public.prevent_arqon_award_rewrite()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if new.arqon_id is distinct from old.arqon_id or new.award_key is distinct from old.award_key
     or new.award_name is distinct from old.award_name or new.award_description is distinct from old.award_description
     or new.award_icon is distinct from old.award_icon or new.rarity is distinct from old.rarity
     or new.reason is distinct from old.reason or new.granted_by is distinct from old.granted_by
     or new.granted_at is distinct from old.granted_at then raise exception 'award_fields_are_immutable'; end if;
  if old.revoked_at is not null then raise exception 'award_already_revoked'; end if;
  if new.revoked_at is null or new.revoked_by is distinct from auth.uid() then raise exception 'invalid_award_revocation'; end if;
  return new;
end;
$$;
create trigger arqon_award_immutable_fields before update on public.arqon_player_awards
for each row execute function public.prevent_arqon_award_rewrite();
create policy "Organizers can revoke ARQON awards"
  on public.arqon_player_awards for update to authenticated
  using (revoked_at is null and (select public.current_organizer_role()) in ('owner','admin','editor'))
  with check (revoked_at is not null and revoked_by=(select auth.uid()) and (select public.current_organizer_role()) in ('owner','admin','editor'));
