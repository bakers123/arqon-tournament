-- ARQON public changelog with organizer-only publishing.
create table if not exists public.changelog_entries (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 4 and 140),
  summary text not null check (char_length(btrim(summary)) between 8 and 280),
  content text not null check (char_length(btrim(content)) between 1 and 8000),
  category text not null default 'improvement'
    check (category in ('feature','improvement','fix','tournament','game')),
  published_at timestamptz not null default now(),
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists changelog_entries_public_date_idx
  on public.changelog_entries (published_at desc, id desc)
  where is_published = true;

alter table public.changelog_entries enable row level security;

drop policy if exists changelog_public_read on public.changelog_entries;
create policy changelog_public_read
  on public.changelog_entries for select to anon, authenticated
  using (is_published = true);

drop policy if exists changelog_organizer_read on public.changelog_entries;
create policy changelog_organizer_read
  on public.changelog_entries for select to authenticated
  using (has_organizer_role('editor'));

drop policy if exists changelog_organizer_insert on public.changelog_entries;
create policy changelog_organizer_insert
  on public.changelog_entries for insert to authenticated
  with check (
    has_organizer_role('editor')
    and (created_by is null or created_by = (select auth.uid()))
  );

drop policy if exists changelog_organizer_update on public.changelog_entries;
create policy changelog_organizer_update
  on public.changelog_entries for update to authenticated
  using (has_organizer_role('editor'))
  with check (has_organizer_role('editor'));

drop policy if exists changelog_organizer_delete on public.changelog_entries;
create policy changelog_organizer_delete
  on public.changelog_entries for delete to authenticated
  using (has_organizer_role('editor'));

grant select on public.changelog_entries to anon, authenticated;
grant insert, update, delete on public.changelog_entries to authenticated;
grant usage, select on sequence public.changelog_entries_id_seq to authenticated;
