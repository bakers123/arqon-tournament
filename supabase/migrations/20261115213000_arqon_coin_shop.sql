-- ARQON Coins wallet and cosmetic shop. VIP is intentionally not a catalog category.
create table if not exists public.arqon_coin_wallets (
  arqon_id bigint primary key references public.profiles(arqon_id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.arqon_coin_transactions (
  id bigint generated by default as identity primary key,
  arqon_id bigint not null references public.profiles(arqon_id) on delete cascade,
  amount bigint not null check (amount <> 0),
  balance_after bigint not null check (balance_after >= 0),
  transaction_type text not null check (transaction_type in ('welcome','activity','achievement','tournament','purchase','refund','admin_adjustment')),
  description text not null default '',
  reference_key text,
  created_at timestamptz not null default now()
);
create unique index if not exists arqon_coin_tx_ref_unique
  on public.arqon_coin_transactions(arqon_id,transaction_type,reference_key)
  where reference_key is not null;
create index if not exists arqon_coin_tx_history_idx
  on public.arqon_coin_transactions(arqon_id,created_at desc);
create table if not exists public.arqon_shop_items (
  id text primary key,
  name text not null,
  description text not null default '',
  category text not null check (category in ('frame','theme','title','badge','seasonal')),
  price bigint not null check (price > 0),
  rarity text not null default 'common' check (rarity in ('common','rare','epic','legendary')),
  preview_style text not null default '',
  is_active boolean not null default true,
  stock_limit integer check (stock_limit is null or stock_limit > 0),
  created_at timestamptz not null default now()
);
create table if not exists public.arqon_shop_inventory (
  id bigint generated by default as identity primary key,
  arqon_id bigint not null references public.profiles(arqon_id) on delete cascade,
  item_id text not null references public.arqon_shop_items(id),
  purchased_at timestamptz not null default now(),
  unique(arqon_id,item_id)
);
alter table public.profiles
  add column if not exists equipped_frame_id text,
  add column if not exists equipped_theme_id text,
  add column if not exists equipped_title_id text;

alter table public.arqon_coin_wallets enable row level security;
alter table public.arqon_coin_transactions enable row level security;
alter table public.arqon_shop_items enable row level security;
alter table public.arqon_shop_inventory enable row level security;

grant select on public.arqon_coin_wallets,public.arqon_coin_transactions,public.arqon_shop_items,public.arqon_shop_inventory to authenticated,anon;
drop policy if exists "Users read own ARQON coin wallet" on public.arqon_coin_wallets;
create policy "Users read own ARQON coin wallet" on public.arqon_coin_wallets for select to authenticated
using (exists(select 1 from public.profiles p where p.arqon_id=arqon_coin_wallets.arqon_id and p.user_id=(select auth.uid())));
drop policy if exists "Users read own ARQON coin transactions" on public.arqon_coin_transactions;
create policy "Users read own ARQON coin transactions" on public.arqon_coin_transactions for select to authenticated
using (exists(select 1 from public.profiles p where p.arqon_id=arqon_coin_transactions.arqon_id and p.user_id=(select auth.uid())));
drop policy if exists "Anyone reads active ARQON shop items" on public.arqon_shop_items;
create policy "Anyone reads active ARQON shop items" on public.arqon_shop_items for select to anon,authenticated using (is_active=true);
drop policy if exists "Users read own ARQON shop inventory" on public.arqon_shop_inventory;
create policy "Users read own ARQON shop inventory" on public.arqon_shop_inventory for select to authenticated
using (exists(select 1 from public.profiles p where p.arqon_id=arqon_shop_inventory.arqon_id and p.user_id=(select auth.uid())));
revoke insert,update,delete on public.arqon_coin_wallets,public.arqon_coin_transactions,public.arqon_shop_items,public.arqon_shop_inventory from anon,authenticated;

