-- Existing profiles receive a wallet and one-time welcome grant. Future profiles are handled by the trigger.
create or replace function public.ensure_arqon_coin_wallet()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.arqon_coin_wallets(arqon_id,balance) values(new.arqon_id,50)
  on conflict(arqon_id) do nothing;
  if not exists(select 1 from public.arqon_coin_transactions t where t.arqon_id=new.arqon_id and t.transaction_type='welcome') then
    insert into public.arqon_coin_transactions(arqon_id,amount,balance_after,transaction_type,description,reference_key)
    values(new.arqon_id,50,50,'welcome','Стартовый бонус ARQON','welcome:'||new.arqon_id::text)
    on conflict do nothing;
  end if;
  return new;
end;
$$;
drop trigger if exists arqon_coin_wallet_on_profile on public.profiles;
create trigger arqon_coin_wallet_on_profile after insert on public.profiles
for each row execute function public.ensure_arqon_coin_wallet();

insert into public.arqon_coin_wallets(arqon_id,balance)
select p.arqon_id,50 from public.profiles p
on conflict(arqon_id) do nothing;
insert into public.arqon_coin_transactions(arqon_id,amount,balance_after,transaction_type,description,reference_key)
select p.arqon_id,50,50,'welcome','Стартовый бонус ARQON','welcome:'||p.arqon_id::text
from public.profiles p
where not exists(select 1 from public.arqon_coin_transactions t where t.arqon_id=p.arqon_id and t.transaction_type='welcome')
on conflict do nothing;

create or replace function public.arqon_shop_buy(p_item_id text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid; v_arqon_id bigint; v_item public.arqon_shop_items%rowtype; v_balance bigint; v_sold integer;
begin
  v_user := auth.uid();
  if v_user is null then raise exception 'Для покупки войди в аккаунт ARQON'; end if;
  select arqon_id into v_arqon_id from public.profiles where user_id=v_user;
  if v_arqon_id is null then raise exception 'Профиль ARQON не найден'; end if;
  select * into v_item from public.arqon_shop_items where id=p_item_id and is_active=true for update;
  if not found then raise exception 'Предмет больше не продаётся'; end if;
  if exists(select 1 from public.arqon_shop_inventory where arqon_id=v_arqon_id and item_id=p_item_id) then
    raise exception 'Этот предмет уже куплен';
  end if;
  if v_item.stock_limit is not null then
    select count(*) into v_sold from public.arqon_shop_inventory where item_id=p_item_id;
    if v_sold>=v_item.stock_limit then raise exception 'Лимитированный предмет закончился'; end if;
  end if;
  insert into public.arqon_coin_wallets(arqon_id,balance) values(v_arqon_id,0) on conflict do nothing;
  select balance into v_balance from public.arqon_coin_wallets where arqon_id=v_arqon_id for update;
  if v_balance < v_item.price then raise exception 'Недостаточно ARQON Coins'; end if;
  update public.arqon_coin_wallets set balance=balance-v_item.price,updated_at=now()
    where arqon_id=v_arqon_id returning balance into v_balance;
  insert into public.arqon_shop_inventory(arqon_id,item_id) values(v_arqon_id,p_item_id);
  insert into public.arqon_coin_transactions(arqon_id,amount,balance_after,transaction_type,description,reference_key)
    values(v_arqon_id,-v_item.price,v_balance,'purchase','Покупка: '||v_item.name,'shop:'||p_item_id);
  return jsonb_build_object('ok',true,'balance',v_balance,'item_id',p_item_id);
end;
$$;
revoke all on function public.arqon_shop_buy(text) from public,anon;
grant execute on function public.arqon_shop_buy(text) to authenticated;

create or replace function public.arqon_shop_equip(p_item_id text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid; v_arqon_id bigint; v_item public.arqon_shop_items%rowtype;
begin
  v_user:=auth.uid();
  if v_user is null then raise exception 'Войди в аккаунт ARQON'; end if;
  select arqon_id into v_arqon_id from public.profiles where user_id=v_user;
  if v_arqon_id is null then raise exception 'Профиль ARQON не найден'; end if;
  if p_item_id is not null then
    select i.* into v_item from public.arqon_shop_items i
    join public.arqon_shop_inventory inv on inv.item_id=i.id and inv.arqon_id=v_arqon_id
    where i.id=p_item_id and i.is_active=true;
    if not found then raise exception 'Предмет не найден в твоём инвентаре'; end if;
    if v_item.category='frame' then update public.profiles set equipped_frame_id=v_item.id where arqon_id=v_arqon_id;
    elsif v_item.category='theme' then update public.profiles set equipped_theme_id=v_item.id where arqon_id=v_arqon_id;
    elsif v_item.category='title' then update public.profiles set equipped_title_id=v_item.id where arqon_id=v_arqon_id;
    else raise exception 'Этот предмет нельзя экипировать'; end if;
  else
    update public.profiles set equipped_frame_id=null,equipped_theme_id=null,equipped_title_id=null where arqon_id=v_arqon_id;
  end if;
  return jsonb_build_object('ok',true);
end;
$$;
revoke all on function public.arqon_shop_equip(text) from public,anon;
grant execute on function public.arqon_shop_equip(text) to authenticated;
